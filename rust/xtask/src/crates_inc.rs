// `cargo xtask crates-inc`: generate the bitbake crates manifest, the
// `SRC_URI += "crate://..."` list, straight from Cargo.lock
// (deterministic, sorted). It is the whole workspace's list, because
// cargo --frozen resolves the whole workspace lockfile whichever member
// a recipe builds; so there is ONE manifest, layer/recipes-core/
// vrx-workspace-crates.inc, required by every cargo recipe, and the gate
// fails when it falls behind Cargo.lock.
//
// Why not cargo-bitbake: 0.3.16 cannot read lock file v4 (the format
// rustc 1.9x writes). The output is identical for this purpose.

use std::path::Path;

/// The one crates manifest every cargo recipe in the layer requires.
pub fn manifest_path() -> std::path::PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../layer/recipes-core/vrx-workspace-crates.inc")
}

/// The crates only an applet needs (plan 0018: camerad's libcamera binding),
/// those in an applet's lock and not in the workspace's. An applet is a
/// standalone crate with its own lock; its recipe requires this list beside
/// the workspace's. Empty while every applet's lock is a subset.
pub fn applets_manifest_path() -> std::path::PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../../layer/recipes-core/vrx-applet-crates.inc")
}

pub fn run(_args: &[String]) -> std::process::ExitCode {
    let mut counts = Vec::new();
    for (out, rendered) in [
        (manifest_path(), render()),
        (applets_manifest_path(), render_applets()),
    ] {
        let written = rendered.and_then(|(body, count)| {
            std::fs::write(&out, body)
                .map_err(|e| format!("writing {}: {e}", out.display()))?;
            Ok(count)
        });
        match written {
            Ok(count) => counts.push((out, count)),
            Err(err) => {
                eprintln!("crates-inc: {err}");
                return std::process::ExitCode::FAILURE;
            }
        }
    }
    for (out, count) in counts {
        println!("wrote {}: {count} crates", out.display());
    }
    std::process::ExitCode::SUCCESS
}

/// The gate's check: the committed manifest is what Cargo.lock renders.
pub fn is_current() -> Result<bool, String> {
    for (path, rendered) in [
        (manifest_path(), render()?),
        (applets_manifest_path(), render_applets()?),
    ] {
        let committed = std::fs::read_to_string(&path)
            .map_err(|e| format!("reading {}: {e}", path.display()))?;
        if committed != rendered.0 {
            return Ok(false);
        }
    }
    Ok(true)
}

type Crate = (String, String, String);

fn render() -> Result<(String, usize), String> {
    // the workspace lock sits at rust/../Cargo.lock
    let lock = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../Cargo.lock");
    let text = std::fs::read_to_string(&lock)
        .map_err(|e| format!("reading {}: {e}", lock.display()))?;
    let crates = registry_crates(&text);
    Ok(body(&crates, "Generated by `cargo xtask crates-inc` — regenerate after any\n# dependency change (Cargo.lock is the source of truth)."))
}

/// Registry crates in applets' locks that the workspace's lock lacks.
fn render_applets() -> Result<(String, usize), String> {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../..");
    let workspace = registry_crates(
        &std::fs::read_to_string(root.join("Cargo.lock"))
            .map_err(|e| format!("reading the workspace lock: {e}"))?,
    );
    let mut extra: Vec<Crate> = Vec::new();
    let mut dirs: Vec<_> = std::fs::read_dir(root.join("applets"))
        .map_err(|e| format!("reading applets/: {e}"))?
        .flatten()
        .map(|e| e.path())
        .collect();
    dirs.sort();
    for dir in dirs {
        let Ok(text) = std::fs::read_to_string(dir.join("Cargo.lock")) else {
            continue;
        };
        extra.extend(
            registry_crates(&text)
                .into_iter()
                .filter(|c| !workspace.contains(c)),
        );
    }
    extra.sort();
    extra.dedup();
    Ok(body(&extra, "Generated by `cargo xtask crates-inc`: the registry crates an\n# applet's own Cargo.lock needs that the workspace's lacks (camerad's\n# libcamera binding). Empty when every applet's lock is a subset."))
}

fn body(crates: &[Crate], header: &str) -> (String, usize) {
    let mut body = format!("# {header}\n\n");
    for (name, version, checksum) in crates {
        body.push_str(&format!(
            "SRC_URI += \"crate://crates.io/{name}/{version}\"\n"
        ));
        body.push_str(&format!(
            "SRC_URI[{name}-{version}.sha256sum] = \"{checksum}\"\n"
        ));
    }
    (body, crates.len())
}

fn registry_crates(text: &str) -> Vec<Crate> {
    let mut crates: Vec<Crate> = Vec::new();
    let mut name: Option<String> = None;
    let mut version: Option<String> = None;
    let mut checksum: Option<String> = None;
    let mut registry = false;
    for line in text.lines().chain(std::iter::once("[[package]]")) {
        // the sentinel at the end flushes the final block
        if line.starts_with("[[") {
            if let (Some(name), Some(version)) = (name.take(), version.take()) {
                if registry {
                    // bitbake refuses to fetch without the checksum;
                    // Cargo.lock carries it
                    let checksum = checksum.take().unwrap_or_default();
                    crates.push((name, version, checksum));
                }
            }
            version = None;
            checksum = None;
            registry = false;
            continue;
        }
        if let Some(rest) = line.strip_prefix("name = ") {
            name = Some(rest.trim_matches('"').to_owned());
        } else if let Some(rest) = line.strip_prefix("version = ") {
            version = Some(rest.trim_matches('"').to_owned());
        } else if let Some(rest) = line.strip_prefix("checksum = ") {
            checksum = Some(rest.trim_matches('"').to_owned());
        } else if line.starts_with("source = ") && line.contains("crates.io-index") {
            registry = true;
        }
    }
    crates.sort();
    crates.dedup();
    crates
}
