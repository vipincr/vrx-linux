// `cargo xtask crates-inc`: generate the bitbake crates manifest for a
// workspace crate — the `SRC_URI += "crate://..."` list every cargo
// recipe needs, straight from Cargo.lock (deterministic, sorted).
//
// Why not cargo-bitbake: 0.3.16 cannot read lock file v4 (the format
// rustc 1.9x writes). The output is identical for this purpose.

use std::path::Path;

pub fn run(args: &[String]) -> std::process::ExitCode {
    let Some(crate_name) = args.first() else {
        eprintln!("usage: cargo xtask crates-inc <crate-name> [out.inc]");
        return std::process::ExitCode::from(64);
    };
    let out = args
        .get(1)
        .cloned()
        .unwrap_or_else(|| format!("{crate_name}-crates.inc"));
    match generate(Path::new(&out)) {
        Ok(count) => {
            println!("wrote {out}: {count} crates");
            std::process::ExitCode::SUCCESS
        }
        Err(err) => {
            eprintln!("crates-inc: {err}");
            std::process::ExitCode::FAILURE
        }
    }
}

fn generate(out: &Path) -> Result<usize, String> {
    // the workspace lock sits at rust/../Cargo.lock
    let lock = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../Cargo.lock");
    let text = std::fs::read_to_string(&lock)
        .map_err(|e| format!("reading {}: {e}", lock.display()))?;

    let mut crates: Vec<(String, String, String)> = Vec::new();
    let mut name: Option<String> = None;
    let mut version: Option<String> = None;
    let mut checksum: Option<String> = None;
    let mut registry = false;
    for line in text.lines().chain(std::iter::once("[[package]]")) {
        // the sentinel at the end flushes the final block
        if line.starts_with("[[") {
            if let (Some(name), Some(version)) = (name.take(), version.take()) {
                if registry {
                    // bitbake refuses to fetch without the checksum;
                    // Cargo.lock carries it
                    let checksum = checksum.take().unwrap_or_default();
                    crates.push((name, version, checksum));
                }
            }
            version = None;
            checksum = None;
            registry = false;
            continue;
        }
        if let Some(rest) = line.strip_prefix("name = ") {
            name = Some(rest.trim_matches('"').to_owned());
        } else if let Some(rest) = line.strip_prefix("version = ") {
            version = Some(rest.trim_matches('"').to_owned());
        } else if let Some(rest) = line.strip_prefix("checksum = ") {
            checksum = Some(rest.trim_matches('"').to_owned());
        } else if line.starts_with("source = ") && line.contains("crates.io-index") {
            registry = true;
        }
    }
    crates.sort();
    crates.dedup();

    let mut body = String::new();
    body.push_str("# Generated by `cargo xtask crates-inc` — regenerate after any\n");
    body.push_str("# dependency change (Cargo.lock is the source of truth).\n\n");
    for (name, version, checksum) in &crates {
        body.push_str(&format!(
            "SRC_URI += \"crate://crates.io/{name}/{version}\"\n"
        ));
        body.push_str(&format!(
            "SRC_URI[{name}-{version}.sha256sum] = \"{checksum}\"\n"
        ));
    }
    std::fs::write(out, body).map_err(|e| format!("writing {}: {e}", out.display()))?;
    Ok(crates.len())
}
