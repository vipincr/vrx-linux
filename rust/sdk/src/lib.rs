// The vrx Rust SDK: what an applet developer imports.
//
// An applet is a store: a pure model (state, actions, a reducer, a
// derived view model), its effects, and a view — joined by one loop
// that is the only writer of the state. The same model compiles into
// a host test: every applet's decisions are testable without a board.
//
// Linux is the kernel; vrx is the OS.

