/// The applet entry point (generated by `vrx new`): seed the store,
/// render the boot view, then — when stdin is a pipe, so the applet is
/// a shell pipeline stage (manifest command.enabled) — apply each
/// newline-delimited JSON action and render after each.
///
/// Printing here is the job: a console applet's stdout IS its render.
#[allow(clippy::print_stdout, clippy::print_stderr)]
pub fn applet_main<A>(applet: A) -> std::process::ExitCode
where
    A: applet::Applet,
    A::Action: serde::de::DeserializeOwned,
{
    let liveness = service::Liveness::new();
    liveness.spawn_watchdog();
    let mut store = store::Store::new(applet);
    let mut sink = RuntimeSink;
    println!("{}", A::render(store.view()));
    // the boot view is out: the applet is usable (its unit's start budget)
    service::notify("READY=1");
    for line in std::io::stdin().lines() {
        let Ok(line) = line else { break };
        if line.trim().is_empty() {
            continue;
        }
        let action: A::Action = match serde_json::from_str(&line) {
            Ok(action) => action,
            Err(err) => {
                eprintln!("vrx: skipping unparseable action: {err}");
                continue;
            }
        };
        liveness.busy();
        store.dispatch(action, &mut sink);
        println!("{}", A::render(store.view()));
        liveness.idle();
    }
    std::process::ExitCode::SUCCESS
}

/// The runtime's effect sink: intents go to vrxhost; a failure
/// degrades to a log line (standalone), never a crash.
struct RuntimeSink;

impl store::EffectSink for RuntimeSink {
    fn deliver(&mut self, effect: &store::Effect) {
        let store::Effect::Intent(intent) = effect;
        match ipc::intent_send(intent.name.clone(), intent.payload.clone()) {
            Ok(_) | Err(crate::ipc::IpcError::NoHost { .. }) => {}
            Err(err) => {
                tracing::warn!(error = %err, intent = %intent.name, "effect failed")
            }
        }
    }
}

