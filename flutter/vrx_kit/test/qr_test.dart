void main() {
  for (final (text, version, mask, rows) in _gold) {
    test('v$version: module for module as segno, its mask forced', () {
      final code = VrxQrCode.encode(text, mask: mask);
      expect(code.version, version);
      final got = [for (var r = 0; r < code.size; r++) [for (var c = 0; c < code.size; c++) code.dark(r, c) ? '1' : '0'].join()];
      expect(got, rows);
    });
  }

  // the mask itself is chosen by the kit's penalty; segno scores masks
  // before it writes the format and version information, so on a symbol
  // with version information its choice can differ, and any mask reads
  test('the chosen mask is one of the eight and the symbol has its size', () {
    for (final (text, version, _, rows) in _gold) {
      final code = VrxQrCode.encode(text);
      expect(code.mask, inInclusiveRange(0, 7));
      expect((code.version, code.size), (version, rows.length));
    }
  });

  test('too long for version 10 is refused', () {
    expect(() => VrxQrCode.encode('x' * 300), throwsFormatException);
  });
}
