#!/usr/bin/env python3
"""Regenerate lib/src/symbols.dart (VrxSymbols): a const IconData per Material Symbol.

The pin lives in one place, the font's recipe
(layer/recipes-fonts/ttf-material-symbols/*.bb): this script reads
MSYM_COMMIT and the codepoints sha256 from it, fetches that exact
codepoints file, checks it, and writes the table. Run from anywhere:

    python3 flutter/vrx_kit/tool/gen_symbols.py
"""
import hashlib
import pathlib
import re
import sys
import urllib.request

ROOT = pathlib.Path(__file__).resolve().parents[3]
RECIPE = next((ROOT / "layer/recipes-fonts/ttf-material-symbols").glob("*.bb"))
OUT = ROOT / "flutter/vrx_kit/lib/src/symbols.dart"
FAMILY = "Material Symbols Rounded"

# Dart reserved words a symbol name could collide with
RESERVED = {
    "abstract", "as", "assert", "async", "await", "break", "case", "catch",
    "class", "const", "continue", "default", "deferred", "do", "dynamic",
    "else", "enum", "export", "extends", "extension", "external", "factory",
    "false", "final", "finally", "for", "get", "if", "implements", "import",
    "in", "interface", "is", "late", "library", "mixin", "new", "null", "on",
    "operator", "part", "required", "rethrow", "return", "set", "show",
    "static", "super", "switch", "sync", "this", "throw", "true", "try",
    "typedef", "var", "void", "while", "with", "yield", "names", "named",
}


def pin():
    text = RECIPE.read_text()
    commit = re.search(r'^MSYM_COMMIT = "([0-9a-f]{40})"', text, re.M).group(1)
    sha = re.search(r'^SRC_URI\[codepoints\.sha256sum\] = "([0-9a-f]{64})"', text, re.M).group(1)
    return commit, sha


def ident(name):
    """A Dart identifier for a symbol name: digits first get a $ prefix,
    reserved words a trailing underscore."""
    if name[0].isdigit():
        return "$" + name
    return name + "_" if name in RESERVED else name


def main():
    commit, sha = pin()
    url = (
        "https://raw.githubusercontent.com/google/material-design-icons/"
        f"{commit}/variablefont/MaterialSymbolsRounded%5BFILL,GRAD,opsz,wght%5D.codepoints"
    )
    data = urllib.request.urlopen(url, timeout=60).read()
    got = hashlib.sha256(data).hexdigest()
    if got != sha:
        sys.exit(f"codepoints sha256 {got} != the recipe's {sha}")
    symbols = []
    for line in data.decode().splitlines():
        name, code = line.split()
        if not re.fullmatch(r"[a-z0-9_]+", name):
            sys.exit(f"unexpected symbol name {name!r}")
        symbols.append((name, int(code, 16)))
    symbols.sort()

    out = [
        "// GENERATED by tool/gen_symbols.py from Material Symbols Rounded",
        f"// at google/material-design-icons {commit}. Do not edit.",
        "",
        "// ignore_for_file: constant_identifier_names, non_constant_identifier_names",
        "",
        "/// vrx's icon set: every Material Symbol (%d), by its name." % len(symbols),
        "///",
        "/// The font is installed system-wide by the ttf-material-symbols",
        "/// recipe and resolved through fontconfig; applets do not bundle it.",
        "/// It is a variable font: [Icon]'s fill, weight, grade and",
        "/// opticalSize select the axes (filled 1 / outlined 0, 100-700).",
        "/// A manifest's display.icon is one of these names.",
        "library;",
        "",
        "import 'package:flutter/widgets.dart';",
        "",
        "const String _family = '%s';" % FAMILY,
        "",
        "abstract final class VrxSymbols {",
        "  /// The symbol for a name (`alarm`, `settings`, `10k`), or null.",
        "  static IconData? named(String name) => byName[name];",
        "",
    ]
    for name, code in symbols:
        out.append(f"  static const IconData {ident(name)} = IconData(0x{code:x}, fontFamily: _family);")
    out.append("")
    out.append("  static const Map<String, IconData> byName = {")
    for name, _ in symbols:
        out.append(f"    '{name}': {ident(name)},")
    out.append("  };")
    out.append("}")
    OUT.write_text("\n".join(out) + "\n")
    print(f"{OUT.relative_to(ROOT)}: {len(symbols)} symbols at {commit[:7]}")


if __name__ == "__main__":
    main()
